#!/usr/bin/env node
"use strict";

const { execFileSync } = require("child_process");
const fs = require("fs");
const path = require("path");

const args = parseArgs(process.argv.slice(2));
const profile = args.profile || process.env.AWS_PROFILE || "HOP42-Sandbox-Developer";
const region = args.region || process.env.AWS_REGION || "us-east-1";
const outPath = path.resolve(args.out || ".env.local");
const secretIds = [
  args.salesforceSecret || "hope1source/hop43/salesforce-jwt",
  args.googleSecret || "hope1source/hop43/google-service-account",
];

const env = {
  AWS_PROFILE: profile,
  AWS_REGION: region,
  BEDROCK_REGION: region,
  BEDROCK_MODEL_ID: "anthropic.claude-sonnet-4-5-20250929-v1:0",
  GMAIL_SUBJECT: "checkins@hope1source.me",
  GMAIL_FROM: "Hope1Source Check-ins <checkins@hope1source.me>",
  GMAIL_REVIEW_RECIPIENT: "checkins@hope1source.me",
  HOP43_ALLOWED_ACCOUNT_NAMES: "Bethel Cafe",
  SF_STAMP_FEEDBACK_EMAIL_SENT: "false",
};

for (const secretId of secretIds) {
  Object.assign(env, readSecretJson(secretId));
}

const lines = [
  "# Generated by scripts/sync-weekly-drafts-env.cjs",
  "# Local developer file only. Do not commit.",
  ...Object.entries(env)
    .filter(([, value]) => value !== undefined && value !== null && String(value).length > 0)
    .map(([key, value]) => `${key}=${quoteEnvValue(String(value))}`),
  "",
];

fs.writeFileSync(outPath, lines.join("\n"), { mode: 0o600 });
fs.chmodSync(outPath, 0o600);
console.log(`Wrote ${outPath} with ${Object.keys(env).length} env keys using AWS profile ${profile}.`);
console.log("No secret values were printed. Keep this file local; it is ignored by git.");

function readSecretJson(secretId) {
  const raw = execFileSync(
    "aws",
    [
      "secretsmanager",
      "get-secret-value",
      "--secret-id",
      secretId,
      "--profile",
      profile,
      "--region",
      region,
      "--query",
      "SecretString",
      "--output",
      "text",
    ],
    { encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] }
  ).trim();

  try {
    return JSON.parse(raw);
  } catch (e) {
    throw new Error(`Secret ${secretId} must contain a JSON object: ${e.message}`);
  }
}

function quoteEnvValue(value) {
  if (/^[A-Za-z0-9_./:@+-]+$/u.test(value)) return value;
  return JSON.stringify(value);
}

function parseArgs(argv) {
  const parsed = {};
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (!arg.startsWith("--")) continue;
    const key = arg.slice(2);
    parsed[key] = argv[i + 1];
    i += 1;
  }
  return parsed;
}
